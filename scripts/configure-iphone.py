#!/usr/bin/env python3
"""Generate local Xcode settings from the shared Apple build configuration."""
import argparse
from pathlib import Path
import sys
from build_config import ROOT, add_config_arguments, resolve_config


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    add_config_arguments(parser)
    parser.add_argument("--output", type=Path, default=ROOT / "iphone/Local.xcconfig")
    args = parser.parse_args()
    config = resolve_config(args)
    args.output.write_text("// Generated by scripts/configure-iphone.py; do not commit.\n" +
        f"DEVELOPMENT_TEAM = {config.apple_team_id}\n" +
        f"CODEX_DROP_IOS_BUNDLE_ID = {config.ios_bundle_id}\n" +
        f"CODEX_DROP_KEYCHAIN_GROUP_SUFFIX = {config.keychain_group_suffix}\n")
    print(f"Wrote {args.output}; now run xcodegen generate --spec iphone/project.yml")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        print(f"iPhone configuration failed: {error}", file=sys.stderr)
        raise SystemExit(1)
